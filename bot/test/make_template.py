"""Искусственный шаблон реестра для тестов бота: лист «общий», шапка в строке 4, подписи в строке 12."""
import sys

import openpyxl

wb = openpyxl.Workbook()
ws = wb.active
ws.title = "общий"
for col, name in enumerate(["№ КС", "№ п/п", "Период", "№ по ведомости", "Наименование документа", "Наименование работ",
                            "Дата", "Номер", "Ед.", "Кол-во", "Место", "С", "По", "Организация", "Реестр №", "Прим."], 1):
    ws.cell(4, col).value = name
ws.cell(12, 1).value = "Сдал:"
wb.save(sys.argv[1])
