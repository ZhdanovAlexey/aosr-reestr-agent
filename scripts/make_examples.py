    put(62, 3, "начала работ")
    put(62, 5, dt(a["start"]))
    put(63, 3, "окончания работ")
    put(63, 5, dt(a["date"]))
    put(64, 1, "6. Работы выполнены в соответствии с")
    put(65, 1, PROJECT)
    put(67, 1, "7. Разрешается производство последующих работ")
