    put(19, 1, "Инженер строительного контроля Иванов И.И.")
    put(21, 1, "Представитель лица, осуществляющего строительство")
    put(22, 1, "Начальник участка Петров П.П.")
    put(24, 1, "Представитель лица, осуществляющего подготовку проектной документации")
    put(25, 1, "Инженер авторского надзора Сидоров С.С.")
