    put(3, 1, "(наименование проектной документации, почтовый или строительный адрес объекта)")
    put(4, 1, "Застройщик, технический заказчик")
    put(5, 1, CUSTOMER)
    put(7, 1, "Лицо, осуществляющее строительство")
    put(8, 1, CONTRACTOR)
    put(10, 1, "Лицо, осуществляющее подготовку проектной документации")
    put(11, 1, DESIGNER)
    put(13, 1, "АКТ")
    put(14, 1, "освидетельствования скрытых работ")
    put(15, 1, a["title"])
    put(16, 1, f"№{a['number']}")
    put(16, 9, dt(a["date"]))
    put(17, 9, "(Дата составления акта)")
