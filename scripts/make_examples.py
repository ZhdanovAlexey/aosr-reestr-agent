def make_scan(path: Path) -> None:
    """Двухстраничный PDF того же акта, что в tests/fixtures/scan_example. Настоящие сканы — картинки без текста."""
    import pymupdf as fitz

    s = SCAN
    p = lambda t: f"<p>{t}</p>"  # noqa: E731
    page1 = "".join([
        p("Объект капитального строительства"), p(OBJECT), p("Застройщик, технический заказчик: " + CUSTOMER),
        p("Лицо, осуществляющее строительство: " + CONTRACTOR),
        "<h3 style='text-align:center'>АКТ<br/>освидетельствования скрытых работ</h3>",
        p(s["title"]), p(f"{s['number']} &nbsp;&nbsp;&nbsp;&nbsp;&nbsp;&nbsp; {s['date']}"),
        p("произвели осмотр работ, выполненных ООО «Ромашка», и составили настоящий акт о нижеследующем:"),
        p("1. К освидетельствованию предъявлены следующие работы:"), *map(p, s["works"]),
        p("2. Работы выполнены по проектной документации " + PROJECT)])
    page2 = "".join([
        p("5. Даты: начала работ 10.08.2024, окончания работ 13.08.2024"),
        p("7. Разрешается производство последующих работ: Устройство насыпи"),
        p("Приложения:"), *(p(f"{i}. {t}") for i, t in enumerate(s["appendices"], 1)),
        p("Представитель застройщика ____________ Иванов И.И."),
        p("Представитель лица, осуществляющего строительство ____________ Петров П.П."),
        p("Представитель лица, выполнившего работы ____________ Сидоров С.С.")])
    doc = fitz.open()
    for html in (page1, page2):
        doc.new_page().insert_htmlbox(fitz.Rect(56, 56, 540, 790), html, css="* {font-size: 10pt;}")
    doc.save(path, garbage=4, deflate=True)


