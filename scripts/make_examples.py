"""Собрать синтетические примеры в examples/: шаблон реестра, книгу актов и PDF акта.

    .venv/bin/python scripts/make_examples.py

Все данные выдуманы: объект, организации, номера, даты и объёмы. Раскладка листов повторяет
типовую форму акта освидетельствования скрытых работ и реестра исполнительной документации,
под которые написан разбор. На этих файлах идут тесты, сквозная проверка и сценарии диалога.
"""
